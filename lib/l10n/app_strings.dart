  static String resolveLanguageCode(BuildContext context, [String? prefOverride]) {
    final langPref = prefOverride ?? AppPrefs.appLanguage;
    if (langPref == 'system' || langPref.isEmpty) {
      final locale = Localizations.localeOf(context);
      if (locale.languageCode == 'zh') {
        return (locale.scriptCode == 'Hant' ||
                locale.countryCode == 'TW' ||
                locale.countryCode == 'HK')
            ? 'zh_tw'
            : 'zh';
      } else if (locale.languageCode == 'ja') {
        return 'ja';
      } else {
        return 'en';
      }
    }
    if (langPref == 'zh-SC' || langPref == 'zh') return 'zh';
    if (langPref == 'zh-TC' || langPref == 'zh_tw') return 'zh_tw';
    if (langPref == 'ja') return 'ja';
    if (langPref == 'en') return 'en';
    return 'zh';
  }

  static bool isSimplifiedChinese(BuildContext context, [String? prefOverride]) {
    return resolveLanguageCode(context, prefOverride) == 'zh';
  }

  static String instructionsAssetPath(BuildContext context, [String? prefOverride]) {
    switch (resolveLanguageCode(context, prefOverride)) {
      case 'zh':
        return 'assets/app_instructions_zh_sc.md';
      case 'zh_tw':
        return 'assets/app_instructions_zh_tc.md';
      case 'ja':
        return 'assets/app_instructions_ja.md';
      default:
        return 'assets/app_instructions_en.md';
    }
  }

  static String get(BuildContext context, String key, [List<dynamic>? args]) {
    final lang = resolveLanguageCode(context);
    final table = _localizedValues[lang] ?? _localizedValues['zh']!;
    var text = table[key] ?? _localizedValues['en']?[key] ?? key;

    if (args != null && args.isNotEmpty) {
      for (final arg in args) {
        text = text.replaceFirst(RegExp(r'%[ds]'), arg.toString());
      }
    }
    return text;
  }
