  static String get(BuildContext context, String key, [List<dynamic>? args]) {
    final langPref = AppPrefs.appLanguage;
    String lang;

    if (langPref == 'system') {
      final locale = Localizations.localeOf(context);
      if (locale.languageCode == 'zh') {
        lang = (locale.scriptCode == 'Hant' || locale.countryCode == 'TW' || locale.countryCode == 'HK')
            ? 'zh_tw'
            : 'zh';
      } else if (locale.languageCode == 'ja') {
        lang = 'ja';
      } else {
        lang = 'en';
      }
    } else {
      lang = langPref;
    }

    final table = _localizedValues[lang] ?? _localizedValues['zh']!;
    var text = table[key] ?? _localizedValues['en']?[key] ?? key;

    if (args != null && args.isNotEmpty) {
      for (final arg in args) {
        text = text.replaceFirst(RegExp(r'%[ds]'), arg.toString());
      }
    }
    return text;
  }
